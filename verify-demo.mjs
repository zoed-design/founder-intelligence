import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1600,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8080/');
await page.getByRole('heading',{name:'Talk to Digger'}).waitFor();
let text=await page.locator('body').innerText();
for(const removed of ['Marubra','Demo Homeowner','framing','Markdown','simulated','Prepare my updates','NSP HOME','Money, clients'])assert.ok(!text.includes(removed),removed);
assert.equal(await page.locator('nav [data-page]').count(),4);
assert.equal(await page.locator('.mascot-canvas').count(),1);
const before=await page.locator('.mascot-canvas').screenshot();
await page.waitForTimeout(600);
const after=await page.locator('.mascot-canvas').screenshot();
assert.ok(!before.equals(after),'Digger must animate while idle');
await page.screenshot({path:'private-demo/roles-initial.png',fullPage:true});
await page.getByRole('button',{name:'Dance',exact:true}).click();
await page.getByRole('button',{name:'Voice off',exact:true}).click();
await page.getByRole('button',{name:'Voice on',exact:true}).click();
await page.locator('#photo-upload').setInputFiles('private-demo/framing.jpg');
await page.locator('.parallel-panes').waitFor();
assert.equal(await page.locator('.team-pane').count(),3);
await page.locator('[data-pane="client"] summary').click();
await page.locator('#review-client').fill('Hi Demo Homeowner, your next project update will follow the inspection.');
const boxes=await page.locator('.team-pane').evaluateAll(es=>es.map(e=>({x:e.getBoundingClientRect().x,y:e.getBoundingClientRect().y})));
assert.ok(boxes.every(b=>Math.abs(b.y-boxes[0].y)<2));
assert.ok(boxes[0].x<boxes[1].x&&boxes[1].x<boxes[2].x);
await page.screenshot({path:'private-demo/roles-parallel.png',fullPage:true});
await page.getByRole('button',{name:'Roo · Team',exact:true}).click();
await page.getByRole('heading',{name:'Talk to Roo',exact:true}).waitFor();
await page.locator('#role-note').fill('What are the next actions?');
await page.getByRole('button',{name:'Send message',exact:true}).click();
await page.getByText('Next actions: confirm readiness',{exact:false}).waitFor();
await page.locator('#draft-body').fill('Internal admin note: supplier margin 20%.');
await page.getByRole('button',{name:'Tally · Client',exact:true}).click();
await page.getByRole('heading',{name:'Talk to Tally',exact:true}).waitFor();
assert.ok((await page.locator('#view').innerText()).includes('your next project update will follow the inspection'));
assert.ok(!(await page.locator('body').innerText()).includes('supplier margin 20%'));
assert.equal(await page.locator('[data-action="export"]').count(),0);
assert.ok(await page.locator('.steps').isHidden());
await page.locator('#role-note').fill('When is the inspection?');
await page.getByRole('button',{name:'Send message',exact:true}).click();
await page.getByText('The team will confirm inspection readiness',{exact:false}).waitFor();
await page.screenshot({path:'private-demo/roles-client.png',fullPage:true});
await page.getByRole('button',{name:'Kooka · Instagram',exact:true}).click();
const social=await page.locator('#draft-body').inputValue();
assert.ok(!/Demo Homeowner|Marubra Street|Example Lender|DEMO-CDC|supplier margin/i.test(await page.locator('#view').innerText()));
await page.locator('#draft-body').fill(social+'\nDemo Homeowner');
await page.getByRole('button',{name:'Digger · Site Manager',exact:true}).click();
await page.getByRole('button',{name:'Approve updates',exact:true}).click();
await page.locator('#pack-error').filter({hasText:'redaction'}).waitFor();
await page.getByRole('button',{name:'Kooka · Instagram',exact:true}).click();
await page.locator('#draft-body').fill(social);
await page.screenshot({path:'private-demo/roles-instagram.png',fullPage:true});
await page.getByRole('button',{name:'Digger · Site Manager',exact:true}).click();
await page.getByRole('button',{name:'Approve updates',exact:true}).click();
const downloaded=page.waitForEvent('download');
await page.getByRole('button',{name:'Download updates',exact:true}).click();
assert.equal((await downloaded).suggestedFilename(),'approved-construction-updates.md');
await page.getByRole('button',{name:'New session',exact:true}).click();
assert.equal(await page.locator('.parallel-panes').count(),0);
assert.ok(!/Marubra|Demo Homeowner|Marubra/.test(await page.locator('#view').innerText()));
// Exercise actual drag/drop, not just the file picker.
const bytes=[...await fs.readFile('private-demo/framing.jpg')];
const transfer=await page.evaluateHandle(bytes=>{const dt=new DataTransfer();dt.items.add(new File([new Uint8Array(bytes)],'site.jpg',{type:'image/jpeg'}));return dt;},bytes);
await page.locator('#photo-drop-zone').dispatchEvent('drop',{dataTransfer:transfer});
await page.locator('.parallel-panes').waitFor();
await page.getByRole('button',{name:'New session',exact:true}).click();
await page.setViewportSize({width:390,height:844});
for(const id of ['workspace','admin','client','social']){
  await page.locator(`[data-page="${id}"]`).click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),id+' mobile overflow');
}
await page.locator('[data-page="workspace"]').click();
await page.screenshot({path:'private-demo/roles-mobile.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log('Browser passed: neutral initial screen, four pages, automatic photo upload and drag/drop, three parallel panes, admin/client conversations, privacy after edit, approval/export, reset, moving mascot, dance/voice and mobile layouts.');
await browser.close();
